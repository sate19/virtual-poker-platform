import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const soundsDir = join(__dirname, "..", "apps", "web", "public", "sounds");
const outFile = join(__dirname, "..", "apps", "web", "src", "lib", "sound-manifest.ts");

if (!existsSync(soundsDir)) {
  console.log("[sound-manifest] sounds dir not found, skipping");
  process.exit(0);
}

const entries = readdirSync(soundsDir, { withFileTypes: true });
const sounds = [];

for (const entry of entries) {
  if (!entry.isDirectory()) continue;
  const mp3Path = join(soundsDir, entry.name, `${entry.name}.mp3`);
  if (existsSync(mp3Path)) {
    sounds.push(entry.name);
  }
}

const content = [
  "// Auto-generated by scripts/generate-sound-manifest.mjs — do not edit manually",
  `// Generated at ${new Date().toISOString()}`,
  `export const AVAILABLE_SOUNDS = ${JSON.stringify(sounds.sort())} as const;`,
  `export type AvailableSound = (typeof AVAILABLE_SOUNDS)[number];`,
  "",
].join("\n");

writeFileSync(outFile, content, "utf-8");
console.log(`[sound-manifest] Found ${sounds.length} sounds: ${sounds.join(", ")}`);
